import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {fileURLToPath,pathToFileURL} from 'node:url';
await import('../offline_guard.mjs');
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const base=path.join(root,'reference/ag1-executable/packages/coding-agent');
const {analyzeAssistantTurnHealth:analyze}=await import(pathToFileURL(path.join(base,'dist/core/turn-health.js')));
const cases=[];
const add=(id,message,volumeRails=true)=>cases.push({id,message,volumeRails,analysis:analyze(message,{applyVolumeRails:volumeRails})});
const message=(text='',tokens=0,stopReason='stop')=>({role:'assistant',content:[{type:'text',text}],usage:{output:tokens},stopReason});
add('normal',message('Done',12));
for(const tokens of [7999,8000,13999,14000])add('tokens-'+tokens,message('answer',tokens));
for(const size of [23999,24000,47999,48000])add('text-'+size,message('x'.repeat(size),10));
add('unicode',message('😀'.repeat(12000),10));
add('string-content',{...message(),content:'x'.repeat(24000)});
for(const reason of ['error','aborted','length','max_tokens'])add(reason,message('answer',0,reason));
add('rails-off',message('x'.repeat(48000),14000),false);
add('truncated-without-volume',message('x'.repeat(48000),14000,'length'),false);
for(const [provider,errorMessage] of [['llamacpp','connection refused'],['local','timeout'],['remote','invalid api key'],['remote','ResourceExhausted'],['remote','worker request limit 5/5'],['remote','actual failure']])add(provider+'-'+errorMessage,{...message('x'.repeat(48000),14000,'error'),provider,errorMessage});
add('tool-work',{...message('',14000),content:[{type:'toolCall',arguments:{path:'out.txt',content:'x'.repeat(56000)}}]});
add('tool-work-plus-prose',{...message('',14000),content:[{type:'toolCall',arguments:{content:'x'.repeat(24000)}},{type:'text',text:'x'.repeat(24000)}]});
add('thinking-excluded',{...message('',10),content:[{type:'thinking',thinking:'x'.repeat(48000)},{type:'text',text:'Done'}]});
add('missing-fields',{role:'assistant'});
const sources=['turn-health.ts','request-failure.ts','model-capability-profile.ts'];
const result=JSON.parse(JSON.stringify({version:1,source_commit:'e30f0b4b238ee5618928bcd17b4571eb046e7038',source_files:sources.map(name=>({path:'packages/coding-agent/src/core/'+name,sha256:createHash('sha256').update(fs.readFileSync(path.join(base,'src/core',name))).digest('hex')})),rows:cases,model_actions:0,network_actions:0}));
const target=path.join(root,'fixtures/runtime/health-oracle.json');
if(process.argv.includes('--capture')){assert(!fs.existsSync(target));fs.writeFileSync(target,JSON.stringify(result,null,2)+'\n');}
else assert.deepEqual(result,JSON.parse(fs.readFileSync(target,'utf8')));
console.log(JSON.stringify({status:'passed',cases:cases.length,model_actions:0,network_actions:0}));
