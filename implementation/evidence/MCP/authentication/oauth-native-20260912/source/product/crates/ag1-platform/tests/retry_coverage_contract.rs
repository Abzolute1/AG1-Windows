#![cfg(target_os = "linux")]
include!("support/session_fixture.rs");

#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn repeated_real_compiler_errors_pause_and_a_source_repair_passes() {
    use ag1_platform::{
        projects::{CheckPort, ProjectPort, Runtime, Toolchains},
        session::adapters::NativeAdapters,
    };
    let mut responses = (0..3)
        .map(|i| calls(vec![(&format!("compile-{i}"), "check", json!({}))]))
        .collect::<Vec<_>>();
    responses.extend([
        calls(vec![(
            "fix-source",
            "write",
            json!({"path":"src/main.rs","content":"fn main() {}\n"}),
        )]),
        calls(vec![("verify-fix", "check", json!({}))]),
        stop(),
    ]);
    let (endpoint, server) = server(responses);
    let f = fixture(&endpoint, "disabled");
    std::fs::write(
        f.root.join("Cargo.toml"),
        "[package]\nname='retry-check-fixture'\nversion='0.1.0'\nedition='2024'\n[workspace]\n",
    )
    .unwrap();
    std::fs::write(
        f.root.join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"retry-check-fixture\"\nversion = \"0.1.0\"\n",
    )
    .unwrap();
    std::fs::create_dir(f.root.join("src")).unwrap();
    let broken = "fn main() { let value: u32 = \"wrong type\"; }\n";
    std::fs::write(f.root.join("src/main.rs"), broken).unwrap();
    let state = f._directory.path().join("project-state");
    std::fs::create_dir(&state).unwrap();
    let cargo = std::path::PathBuf::from(env!("CARGO"))
        .canonicalize()
        .unwrap();
    let toolchain = cargo.parent().unwrap().parent().unwrap().to_path_buf();
    let runtime = Runtime::load(
        f.workspace.clone(),
        WorkspaceService::new().unwrap().register(&state).unwrap(),
        env!("CARGO_BIN_EXE_ag1-process-host").as_ref(),
        Toolchains {
            node: None,
            npm: None,
            cargo: Some(cargo),
            rustc: Some(toolchain.join("bin/rustc")),
            godot: None,
            mounts: vec![toolchain],
        },
    )
    .unwrap();
    let project = Arc::new(Mutex::new(ProjectPort::Check(Box::new(CheckPort {
        runtime,
        kind: ag1_core::projects::Kind::Rust,
    }))));
    let adapters = NativeAdapters {
        project: Some(project.clone()),
        ..Default::default()
    };
    let mut registry = Registry::builtins().unwrap();
    registry
        .activate(
            &["check".into(), "write".into()],
            &adapters.available_names().into_iter().collect(),
        )
        .unwrap();
    let tools = registry
        .public_tools()
        .into_iter()
        .filter(|t| t["name"] == "check" || t["name"] == "write")
        .collect();
    f.host
        .select_tools(
            "retry-check-tools",
            "retry-check-tools",
            NOW,
            tools,
            &ignore,
        )
        .await
        .unwrap();
    let runner = Arc::new(FileRunner {
        files: f.files.files.clone(),
        adapters,
        registry: Arc::new(registry),
        policy: f.files.policy.clone(),
        policy_revision: 1,
        approvals: Arc::new(RejectApproval),
        store: f.store.clone(),
        origin: "session".into(),
        timestamp: NOW.into(),
        clock: Arc::new(FixedClock),
        tool_timeout: Duration::from_secs(60),
    });
    let first = f
        .host
        .run(input(), &Resolver::new(false), runner.clone(), &ignore)
        .await
        .unwrap();
    assert_eq!(first.generations, 3);
    assert_eq!(first.assistant["nativePolicy"], "repetition_guard");
    assert!(
        first
            .assistant
            .to_string()
            .contains("same compiler diagnostics")
    );
    assert_eq!(
        std::fs::read_to_string(f.root.join("src/main.rs")).unwrap(),
        broken
    );
    let mut next = input();
    next.command = "repair-after-pause".into();
    let second = f
        .host
        .run(next, &Resolver::new(false), runner, &ignore)
        .await
        .unwrap();
    assert_eq!(second.generations, 3);
    let project = project.lock().unwrap();
    let ProjectPort::Check(port) = &*project else {
        panic!()
    };
    let history = port.runtime.history().unwrap();
    assert_eq!(history.len(), 4);
    assert_eq!(
        history
            .iter()
            .filter(|r| r.exits == vec![Some(101)])
            .count(),
        3
    );
    assert_eq!(
        history.iter().filter(|r| r.exits == vec![Some(0)]).count(),
        1
    );
    assert!(f.host.settled().unwrap());
    assert_eq!(server.join().unwrap().len(), 6);
}
